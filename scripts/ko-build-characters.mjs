import { writeFile, readFile, mkdir } from 'node:fs/promises';
import { tsImport } from 'tsx/esm/api';
import source from './ko-character-source.mjs';
const {loadFranchise} = await tsImport('../src/services/anilistClient.ts',import.meta.url);
const directory = '/tmp/animegraph-p5-pools';
await mkdir(directory,{recursive:true});
const dictionary={}, report=[];
for(const group of source){
 const file=`${directory}/${group.anilistId}.json`;
 let anime;
 if(process.argv.includes('--cached')){try{anime=JSON.parse(await readFile(file,'utf8'));}catch{}}
 if(!anime){
  const original=globalThis.fetch;let requests=0;
  globalThis.fetch=(...args)=>{if(String(args[0]).includes('graphql.anilist.co'))requests++;return original(...args);};
  try{anime=await loadFranchise(group.anilistId);}finally{globalThis.fetch=original;}
  console.log(`FETCH ${group.anilistId}: ${anime.franchise?.members.length??1} members / ${requests} requests`);
  await writeFile(file,JSON.stringify(anime));
 }
 const pool=anime.fullCastPool??anime.cast, unmatched=[];let matched=0;
 for(const {en,ko}of group.names){
  const hits=pool.filter(c=>c.character.name.full.toLowerCase()===en.toLowerCase());
  if(!hits.length){unmatched.push(en);continue;}
  for(const c of hits){if(dictionary[c.character.id]&&dictionary[c.character.id]!==ko)throw new Error(`Conflicting ko for ${en}`);dictionary[c.character.id]=ko;}
  matched++;
 }
 console.log(`${group.anilistId} ${anime.title.romaji}: ${matched}/${group.names.length}; unmatched: ${unmatched.join(', ')||'none'}`);
 report.push({id:group.anilistId,title:anime.title.romaji,matched,total:group.names.length,unmatched});
}
await writeFile(new URL('../src/data/koreanCharacters.ts',import.meta.url),`// Generated by scripts/ko-build-characters.mjs from ko-character-source.mjs. Do not edit by hand.\nexport const KO_CHARACTERS: Record<number, string> = ${JSON.stringify(dictionary,null,2)};\n`);
await writeFile(`${directory}/report.json`,JSON.stringify(report,null,2));
console.log(`Wrote ${Object.keys(dictionary).length} unique AniList character ids.`);
