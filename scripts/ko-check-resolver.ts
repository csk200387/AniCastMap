import {readFile,writeFile} from 'node:fs/promises';
import {cachedKoreanName,koreanNameCacheSnapshot,resolveKoreanNames} from '../src/services/koreanNameResolver';
import type {KoreanNameQuery} from '../src/services/koreanNameResolver';
import {curatedKoreanName} from '../src/services/localize';
const original=globalThis.fetch;
globalThis.fetch=async(input,init)=>{const start=Date.now();try{const r=await original(input,init);console.log('HTTP',r.status,Date.now()-start,'ms',String(init?.body).length,'request bytes');return r;}catch(e){console.log('ERROR',Date.now()-start,String(e));throw e;}};
for(const id of [154587,113415]){
 const anime=JSON.parse(await readFile(`/tmp/animegraph-p5-pools/${id}.json`,'utf8'));
 const queries: KoreanNameQuery[]=[];
 for(const c of anime.fullCastPool){
  for(const [kind,p] of [['character',c.character],['voiceActor',c.voiceActor],...(c.subVoiceActors??[]).map(s=>['voiceActor',s.voiceActor])]){
   if(!p)continue;const name={...p.name,ko:undefined};
   if(process.argv.includes('--voices-only') && kind!=='voiceActor')continue;
   if(!curatedKoreanName(name,{kind,id:p.id}))queries.push({kind,id:p.id,native:name.native,full:name.full});
  }
 }
 const unique=[...new Map(queries.map(q=>[`${q.kind}:${q.native}`,q])).values()];
 const stats=await resolveKoreanNames(unique);const resolved=unique.flatMap(query=>{const ko=cachedKoreanName(query);return ko?[{query,ko}]:[];});
 console.log(`${id}: ${resolved.length}/${unique.length} available; network ${stats.hits}/${stats.unknown} unknown`);
 for(const {query,ko}of resolved)console.log(`${query.kind} ${query.full} (${query.native}) → ${ko}`);
}

if(process.argv.includes('--write-cache'))await writeFile(new URL('../src/data/koreanNameCache.ts',import.meta.url),`// Generated by scripts/ko-check-resolver.ts --write-cache. Exact Wikidata ja labels + Q5/Q95074 checks.
export const STATIC_KOREAN_NAMES: Record<string, {ko: string | null; expires: number}> = ${JSON.stringify(koreanNameCacheSnapshot(),null,2)};\n`);
